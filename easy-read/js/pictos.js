  const PICTOS = LIST.map(([label, emoji, cat, words]) => ({ label, emoji, cat, words }));

  // 찾기용: 낱말이 긴 것부터
  const INDEX = [];
  PICTOS.forEach(p => p.words.forEach(w => INDEX.push({ w, p })));
  INDEX.sort((a, b) => b.w.length - a.w.length);

  // 한 글자 낱말(물·옷·책·산·눈·약 등)은 다른 낱말의 일부일 때가 많아 앞뒤를 확인합니다.
  const SHORT_OK_AFTER = /^($|[\s,.·、)\]을를은는이가도과와랑만이나에의(])/;
  const SHORT_OK_BEFORE = /(^|[\s,.·、(\[:：])$/;

  /**
   * 글에서 그림 낱말을 모두 찾습니다. 겹치는 곳은 긴 낱말을 씁니다.
   * @returns {{label,emoji,cat,word,index}[]} 글에 나온 순서
   */
  function find(text, opts = {}) {
    if (!text) return [];
    const taken = new Array(text.length).fill(false);
    const hits = [];
    for (const { w, p } of INDEX) {
      if (opts.cat && !opts.cat.includes(p.cat)) continue;
      let from = 0;
      for (;;) {
        const i = text.indexOf(w, from);
        if (i < 0) break;
        from = i + 1;
        if (w.length === 1) {
          if (!SHORT_OK_BEFORE.test(text.slice(Math.max(0, i - 1), i))) continue;
          if (!SHORT_OK_AFTER.test(text.slice(i + 1, i + 2))) continue;
        }
        let free = true;
        for (let k = i; k < i + w.length; k++) if (taken[k]) { free = false; break; }
        if (!free) continue;
        for (let k = i; k < i + w.length; k++) taken[k] = true;
        hits.push({ label: p.label, emoji: p.emoji, cat: p.cat, word: w, index: i });
      }
    }
    return hits.sort((a, b) => a.index - b.index);
  }

  /** 글에 맞는 첫 그림. 없으면 fallback */
  function pick(text, fallback, opts) {
    const hit = find(text, opts)[0];
    return hit ? hit.emoji : fallback;
  }

  /** 마지막 그림 — '우리 학교 운동장'처럼 뒤 낱말이 중심일 때 */
  function pickLast(text, fallback, opts) {
    const hits = find(text, opts);
    return hits.length ? hits[hits.length - 1].emoji : fallback;
  }

  return { PICTOS, find, pick, pickLast };
